// Generates docs/cli-reference.md from the Commander registrations in
// core_engine/src/cli/run.ts. GENERATED — never hand-edit. Regenerate: npm run docs:index.
const fs = require("fs");
const path = require("path");
const { ROOT, read } = require("./lib/ast");

const SRC = path.join(ROOT, "core_engine", "src", "cli", "run.ts");
const OUT = "docs/cli-reference.md";

// Sub-parent vars: `const importCmd = program.command('import')` → importCmd maps to `import`.
function findSubParents(src) {
  const map = {}; // varName -> command name
  const re = /const\s+(\w+)\s*=\s*program\s*\.command\(\s*(['"])([^'"]+)\2\s*\)/g;
  let m;
  while ((m = re.exec(src))) map[m[1]] = m[3].split(/\s+/)[0];
  return map;
}

function parseOptions(block) {
  const opts = [];
  const re = /\.(requiredOption|option)\(\s*(['"])(.*?)\2\s*,\s*(['"])([\s\S]*?)\4\s*(?:,\s*([\s\S]*?))?\)/g;
  let m;
  while ((m = re.exec(block))) {
    opts.push({
      required: m[1] === "requiredOption",
      flag: m[3],
      desc: m[5].replace(/\s+/g, " ").trim(),
      default: (m[6] || "").trim()
    });
  }
  return opts;
}

function generate() {
  const src = read(SRC);
  const subParents = findSubParents(src);

  // All `.command('sig')` sites with their receiver identifier.
  const cmdRe = /(\w+)\s*\.command\(\s*(['"])([^'"]+)\2\s*\)/g;
  const sites = [];
  let m;
  while ((m = cmdRe.exec(src))) {
    sites.push({ receiver: m[1], sig: m[3], start: m.index, end: cmdRe.lastIndex });
  }

  // Each command's chain = source from its .command( to the next .command( site.
  const commands = sites.map((s, i) => {
    const blockEnd = i + 1 < sites.length ? sites[i + 1].start : src.length;
    const block = src.slice(s.end, blockEnd);
    const descM = block.match(/\.description\(\s*(['"])([\s\S]*?)\1\s*\)/);
    const parent = subParents[s.receiver] || null; // receiver is a sub-parent var → nest
    return {
      sig: s.sig,
      name: s.sig.split(/\s+/)[0],
      args: s.sig.split(/\s+/).slice(1).join(" "),
      parent,
      description: descM ? descM[2].replace(/\s+/g, " ").trim() : "",
      options: parseOptions(block)
    };
  });

  const top = commands.filter((c) => !c.parent);
  const childrenOf = (name) => commands.filter((c) => c.parent === name);

  const lines = [];
  lines.push("<!-- GENERATED by tools/gen-cli-reference.js — DO NOT EDIT. Regenerate: npm run docs:index -->");
  lines.push("# CLI Reference\n");
  lines.push("> Derived from the Commander registrations in `core_engine/src/cli/run.ts`. Every command,");
  lines.push("> argument, and option below is generated from the source — it cannot drift from the code.\n");
  lines.push("Run any command via `npm run cli -- <command> [options]` (or the `k6-framework` binary).\n");
  lines.push("Running with no subcommand on a TTY launches the interactive panel; non-TTY prints help.\n");

  // Index
  lines.push("## Commands\n");
  lines.push("| Command | Purpose |");
  lines.push("|---------|---------|");
  for (const c of top) {
    const kids = childrenOf(c.name);
    lines.push(`| \`${c.sig}\` | ${c.description || "—"} |`);
    for (const k of kids) lines.push(`| \`${c.name} ${k.sig}\` | ${k.description || "—"} |`);
  }
  lines.push("");

  const renderCmd = (c, prefix = "") => {
    const heading = prefix ? `### \`${prefix} ${c.sig}\`` : `### \`${c.sig}\``;
    lines.push(heading);
    if (c.description) lines.push(`\n${c.description}\n`);
    if (c.args) lines.push(`**Arguments:** \`${c.args}\`\n`);
    if (c.options.length) {
      lines.push("| Option | Required | Default | Description |");
      lines.push("|--------|----------|---------|-------------|");
      for (const o of c.options) {
        const def = o.default && !/process\.|path\./.test(o.default) ? `\`${o.default.replace(/['"]/g, "")}\`` : "";
        lines.push(`| \`${o.flag}\` | ${o.required ? "yes" : "no"} | ${def} | ${o.desc} |`);
      }
      lines.push("");
    }
  };

  lines.push("## Reference\n");
  for (const c of top) {
    renderCmd(c);
    for (const k of childrenOf(c.name)) renderCmd(k, c.name);
  }

  const content = lines.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
  const full = path.join(ROOT, OUT);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, content, "utf8");
  return [OUT];
}

module.exports = { generate };
if (require.main === module) generate().forEach((f) => console.log("wrote", f));
