// Generates docs/presentation/architecture-deck.md — a Marp-renderable slide deck built entirely
// from the L4 indexes (framework_map, feature_index, dependency_graph, file_index). GENERATED —
// never hand-edit. Regenerate: npm run docs:index. The deck cannot drift from the architecture.
const fs = require("fs");
const path = require("path");
const { ROOT } = require("./lib/ast");

const OUT = "docs/presentation/architecture-deck.md";

function loadJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
}

function layerOfPath(p) {
  const m = p.match(/^core_engine\/src\/([^/]+)\//);
  return m ? m[1] : "root";
}

function generate() {
  const features = loadJson("ai_generated/feature_index.json");
  const fileIndex = loadJson("ai_generated/file_index.json");
  const dep = loadJson("ai_generated/dependency_graph.json");

  const fileCount = fileIndex.length;
  const layers = [...new Set(fileIndex.map((f) => f.layer))].sort();
  const fullEdds = features.filter((f) => f.tier === "full");

  // Aggregate file-level dependency edges to layer-level (drop self-loops), dedupe, sort.
  const fileLayer = new Map(fileIndex.map((f) => [f.path, f.layer]));
  const layerEdges = new Set();
  for (const e of dep.edges) {
    const a = fileLayer.get(e.from) || layerOfPath(e.from);
    const b = fileLayer.get(e.to) || layerOfPath(e.to);
    if (a && b && a !== b) layerEdges.add(`${a} --> ${b}`);
  }
  const edgeLines = [...layerEdges].sort();

  const s = [];
  s.push("<!-- GENERATED by tools/gen-presentation.js — DO NOT EDIT. Regenerate: npm run docs:index -->");
  s.push("<!-- Render as slides with Marp (VS Code “Marp for VS Code” or `marp architecture-deck.md`). Also readable as plain Markdown. -->");
  s.push("---");
  s.push("marp: true");
  s.push("theme: default");
  s.push("paginate: true");
  s.push("---");
  s.push("");
  // Slide 1 — title
  s.push("# K6-PerfFramework");
  s.push("### Architecture at a glance");
  s.push("");
  s.push(`**${features.length}** features · **${fileCount}** source files · **${layers.length}** layers · **${fullEdds.length}** deep-dive EDDs`);
  s.push("");
  s.push("*This deck is generated from the code indexes — it cannot drift.*");
  s.push("");
  s.push("---");
  s.push("");
  // Slide 2 — the two worlds
  s.push("## Two execution worlds");
  s.push("");
  s.push("- **Node orchestration** — before/after the run: `cli` → `config` → `scenario` → `execution` → `reporting`/`debug`");
  s.push("- **k6 runtime (goja)** — during the run, per VU: `utils/*` imported via `dist/index.js` (no Node built-ins)");
  s.push("");
  s.push("> k6 loads compiled `dist/`, not `.ts`. Rebuild after VU-side edits.");
  s.push("");
  s.push("---");
  s.push("");
  // Slide 3 — layer dependency graph (generated)
  s.push("## Layer dependency map");
  s.push("");
  s.push("```mermaid");
  s.push("flowchart LR");
  for (const line of edgeLines) s.push(`  ${line}`);
  s.push("```");
  s.push("");
  s.push("*Aggregated from `ai_generated/dependency_graph.json` (file edges → layer edges).*");
  s.push("");
  s.push("---");
  s.push("");
  // Slide 4 — features → owners (generated)
  s.push("## Features & owners");
  s.push("");
  s.push("| Feature | Entry | Tier |");
  s.push("|---------|-------|------|");
  for (const f of [...features].sort((a, b) => a.feature.localeCompare(b.feature))) {
    s.push(`| ${f.title} | \`${f.entry.replace("core_engine/src/", "")}\` | ${f.tier} |`);
  }
  s.push("");
  s.push("---");
  s.push("");
  // Slide 5 — deep dives
  s.push("## Highest-risk subsystems (full EDDs)");
  s.push("");
  for (const f of fullEdds) {
    const risks = f.risks && f.risks.length ? ` — risks: ${f.risks.join(", ")}` : "";
    s.push(`- **${f.title}** → \`${f.edd}\`${risks}`);
  }
  s.push("");
  s.push("---");
  s.push("");
  // Slide 6 — documentation system
  s.push("## Documentation is source code");
  s.push("");
  s.push("| Layer | Where | Role |");
  s.push("|-------|-------|------|");
  s.push("| L1 | `ai_context/` + `FrameworkAtlas.md` | routing / rules |");
  s.push("| L2 | `engineering_docs/` | EDDs (reverse-engineered from code) |");
  s.push("| L3 | `docs/` | published user docs |");
  s.push("| L4 | `ai_generated/*.json` | generated indexes |");
  s.push("");
  s.push("Outdated docs are bugs — a staleness gate (`npm run docs:check`) keeps generated parts honest.");
  s.push("");
  s.push("---");
  s.push("");
  // Slide 7 — start here
  s.push("## Start here");
  s.push("");
  s.push("- Navigate: `FrameworkAtlas.md`");
  s.push("- Onboard: `docs/onboarding/day-1.md`");
  s.push("- Go deep: `engineering_docs/edd/`");
  s.push("");

  const content = s.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
  const full = path.join(ROOT, OUT);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, content, "utf8");
  return [OUT];
}

module.exports = { generate };
if (require.main === module) generate().forEach((f) => console.log("wrote", f));
